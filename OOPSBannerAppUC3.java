/**
 * OOPSBannerApp UC3 - Banner using String.join()
 */

public class OOPSBannerAppUC3 {
    public static void main(String[] args) {

        System.out.println(String.join(" ", " *** ", " *** ", "**** ", "**** "));
        System.out.println(String.join(" ", "*   *", "*   *", "*   *", "*    "));
        System.out.println(String.join(" ", "*   *", "*   *", "*   *", "*    "));
        System.out.println(String.join(" ", "*   *", "*   *", "**** ", " *** "));
        System.out.println(String.join(" ", "*   *", "*   *", "*    ", "    *"));
        System.out.println(String.join(" ", "*   *", "*   *", "*    ", "    *"));
        System.out.println(String.join(" ", " *** ", " *** ", "*    ", "**** "));

    }
}